#!/usr/bin/env bash
# push.sh — build + push the editor images to GHCR by digest, then pin versions.env.
#
# Prereq (ONE-TIME, you must do this — adds the package scopes to gh):
#   gh auth refresh -h github.com -s write:packages,read:packages
#
# MULTI-ARCH (D14, executed 2026-08-16): the fleet pointer pins the manifest
# INDEX digest — amd64 (ThinkPads) + arm64 (d1/Spark, built natively there).
# This script builds+pushes the NATIVE arch of the machine it runs on; the
# index is stitched afterwards from the per-arch digests (Route A,
# df:docs/protocols/image-multiarch.md):
#   docker buildx imagetools create -t $REG/nvim:$TAG -t $REG/nvim:latest \
#     $REG/nvim@<amd64-digest> $REG/nvim@<arm64-digest>       # same for nvim-base
# versions.env is only written when the pinned digest IS an index — a per-arch
# digest from a single-arch push must never clobber the fleet pointer (guard
# below). Order matters: base first (capture its digest), pin the thin FROM to
# that digest, then thin.
set -euo pipefail

REG="ghcr.io/advl"
BASE="$REG/nvim-base"
THIN="$REG/nvim"
GIT_SHA="$(git rev-parse HEAD)"
# calver, human-readable; the digest is the truth. OVERRIDABLE because a second
# push on the same day would otherwise re-point the existing date tag at a new
# image — which is why the git log carries hand-edited 2026.08.03a/b suffixes
# that never existed on GHCR. Pass the suffix instead:  TAG=2026.08.03c push.sh
TAG="${TAG:-$(date -u +%Y.%m.%d)}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

# ENGINE. This fleet is rootless PODMAN — on NixOS `docker` is a symlink to it
# (v3.sh detects the same dockerCompat shim). Podman aliases `buildx build` to
# buildah, which has neither --provenance nor --metadata-file, so the buildx
# path fails outright here. Detect and use each engine's native build+push;
# both capture the REGISTRY manifest digest, which is what versions.env pins.
ENGINE=docker
if docker buildx version 2>/dev/null | grep -qi buildah; then ENGINE=podman; fi
echo "==> engine: $ENGINE"

# build_and_push <repo> <digest-outfile> [build args...]
build_and_push() {
  local repo="$1" digestfile="$2"; shift 2
  if [ "$ENGINE" = podman ]; then
    podman build "$@" -t "$repo:$TAG" -t "$repo:latest" .
    podman push --digestfile "$digestfile" "$repo:$TAG"
    podman push "$repo:latest"
  else
    docker buildx build "$@" -t "$repo:$TAG" -t "$repo:latest" \
      --provenance=false --metadata-file /tmp/push-meta.json --push .
    jq -r '."containerimage.digest"' /tmp/push-meta.json > "$digestfile"
  fi
}

echo "==> GHCR login (gh token)"
gh auth token | "$ENGINE" login ghcr.io -u "$(gh api user --jq .login)" --password-stdin

# SKIP_BASE=1 reuses the base digest already pinned in versions.env. The base is
# apt + npm, so a rebuild can silently pull newer upstreams and re-pin the fleet
# to a base nothing has run yet. A config-layer edit (the common case — see
# Dockerfile's header) must NOT drag that along. Omit it when the base changed.
if [ -n "${SKIP_BASE:-}" ] && [ -f versions.env ]; then
  BASE_DIGEST="$(sed -n 's/^NVIM_BASE_IMAGE=.*@//p' versions.env)"
  [ -n "$BASE_DIGEST" ] || { echo "SKIP_BASE: no NVIM_BASE_IMAGE digest in versions.env" >&2; exit 1; }
  echo "==> SKIP_BASE: reusing base@$BASE_DIGEST (not rebuilt, not re-pushed)"
else
  echo "==> build + push BASE ($BASE:$TAG)"
  build_and_push "$BASE" /tmp/base.digest -f Dockerfile.base --target final \
    --build-arg GIT_SHA="$GIT_SHA"
  BASE_DIGEST="$(cat /tmp/base.digest)"
  echo "    base digest: $BASE_DIGEST"
fi

echo "==> build + push THIN ($THIN:$TAG) FROM base@$BASE_DIGEST"
build_and_push "$THIN" /tmp/thin.digest \
  --build-arg BASE_IMAGE="$BASE@$BASE_DIGEST" \
  --build-arg GIT_SHA="$GIT_SHA"
THIN_DIGEST="$(cat /tmp/thin.digest)"
echo "    thin digest: $THIN_DIGEST"

# ---- D14 GUARD: only an INDEX digest may enter versions.env -----------------
# A native single-arch push (this script's normal mode) yields a per-arch
# manifest digest. Writing that would re-pin the whole fleet to ONE arch and
# silently break the other. The fleet pointer moves only at index-stitch time.
media_type() {
  "$ENGINE" buildx imagetools inspect --raw "$1" 2>/dev/null \
    | sed -n 's/.*"mediaType"[^"]*"\([^"]*\)".*/\1/p' | head -1
}
THIN_MT="$(media_type "$THIN@$THIN_DIGEST")"
case "$THIN_MT" in
  *index*|*manifest.list*)
    echo "==> write versions.env (the fleet pointer; v3 reads NVIM_IMAGE from here)"
    cat > versions.env <<EOF
# Generated by bin/push.sh — the digest-pinned editor the fleet pulls.
# v3 reads NVIM_IMAGE from here. The digest is the immutable truth; the tag is
# human-readable. Bump by re-running push.sh and committing this file.
# D14: manifest-list (INDEX) digests — one string, every arch. Never re-pin
# to a per-arch digest (df:docs/protocols/image-multiarch.md invariant).
NVIM_IMAGE=$THIN@$THIN_DIGEST
NVIM_BASE_IMAGE=$BASE@$BASE_DIGEST
NVIM_TAG=$TAG
NVIM_GIT_SHA=$GIT_SHA
NVIM_ARCHS="amd64 arm64"
EOF
    cat versions.env
    ;;
  *)
    echo "==> versions.env NOT written: pushed digest is a per-arch manifest ($THIN_MT)."
    echo "    This arch's digests (stitch the index from any machine, then pin THAT):"
    echo "      thin: $THIN@$THIN_DIGEST"
    echo "      base: $BASE@$BASE_DIGEST"
    echo "    $ENGINE buildx imagetools create -t $THIN:$TAG -t $THIN:latest \\"
    echo "        $THIN@<amd64-digest> $THIN@<arm64-digest>   # same for base, then"
    echo "    write versions.env with the two INDEX digests + NVIM_ARCHS."
    ;;
esac

echo "==> done. Make the GHCR packages public if the fleet pulls unauthenticated:"
echo "    gh api -X PATCH /user/packages/container/nvim ... (or the package settings page)."