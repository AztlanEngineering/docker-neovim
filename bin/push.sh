#!/usr/bin/env bash
# push.sh — build + push the editor images to GHCR by digest, then pin versions.env.
#
# Prereq (ONE-TIME, you must do this — adds the package scopes to gh):
#   gh auth refresh -h github.com -s write:packages,read:packages
#
# Fleet is all x86_64 (ThinkPads) -> amd64-only, no multi-arch. Order matters:
# base first (capture its digest), pin the thin FROM to that digest, then thin.
set -euo pipefail

REG="ghcr.io/advl"
BASE="$REG/nvim-base"
THIN="$REG/nvim3"
GIT_SHA="$(git rev-parse HEAD)"
TAG="$(date -u +%Y.%m.%d)"   # calver, human-readable; the digest is the truth
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

echo "==> GHCR login (gh token)"
gh auth token | docker login ghcr.io -u "$(gh api user --jq .login)" --password-stdin

echo "==> build + push BASE ($BASE:$TAG)"
docker buildx build -f Dockerfile.base --target final \
  --build-arg GIT_SHA="$GIT_SHA" \
  -t "$BASE:$TAG" -t "$BASE:latest" \
  --provenance=false \
  --metadata-file /tmp/base-meta.json \
  --push .
BASE_DIGEST="$(jq -r '."containerimage.digest"' /tmp/base-meta.json)"
echo "    base digest: $BASE_DIGEST"

echo "==> build + push THIN ($THIN:$TAG) FROM base@$BASE_DIGEST"
docker buildx build \
  --build-arg BASE_IMAGE="$BASE@$BASE_DIGEST" \
  --build-arg GIT_SHA="$GIT_SHA" \
  -t "$THIN:$TAG" -t "$THIN:latest" \
  --provenance=false \
  --metadata-file /tmp/thin-meta.json \
  --push .
THIN_DIGEST="$(jq -r '."containerimage.digest"' /tmp/thin-meta.json)"
echo "    thin digest: $THIN_DIGEST"

echo "==> write versions.env (the fleet pointer; v3 reads NVIM_IMAGE from here)"
cat > versions.env <<EOF
# Generated by bin/push.sh — the digest-pinned editor the fleet pulls.
# v3 reads NVIM_IMAGE from here. The digest is the immutable truth; the tag is
# human-readable. Bump by re-running push.sh and committing this file.
NVIM_IMAGE=$THIN@$THIN_DIGEST
NVIM_BASE_IMAGE=$BASE@$BASE_DIGEST
NVIM_TAG=$TAG
NVIM_GIT_SHA=$GIT_SHA
EOF

echo "==> done. Review + commit versions.env, and make the GHCR packages public if"
echo "    the fleet pulls unauthenticated:  gh api -X PATCH /user/packages/container/nvim3 ..."
echo "    (or via the GitHub package settings page)."
cat versions.env